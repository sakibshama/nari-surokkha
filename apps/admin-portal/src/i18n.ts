/**
 * Fill `{name}` placeholders in an (already translated) string:
 * `fmt(t('Location: {coords}'), { coords: '23.8, 90.4' })`.
 */
export function fmt(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Returns a translator bound to the current language. */
export function useT() {
  const lang = useLangStore((s) => s.lang);
  return (s: string): string => (lang === 'bn' ? translations[s] ?? s : s);
}

/** Non-hook translator for code outside components (toasts from services…). */
export function tr(s: string): string {
  return useLangStore.getState().lang === 'bn' ? translations[s] ?? s : s;
}
